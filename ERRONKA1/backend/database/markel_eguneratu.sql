-- Markel.sql (dump zaharra, DATU BASEA.docx-arena) --> gaur egungo eskema
-- ===========================================================================
--
-- ZERTARAKO:
--   Proiektuaren kodea (models/models.py) eta Urkoren dump-a (powerbank_erreserba.sql)
--   eskema berriarekin eginda daude. Markelen datu-baseak, ordea, eskema zaharra
--   dauka, eta horregatik API-a errore hauekin erortzen da:
--
--     column "activo" of relation "erabiltzaileak" does not exist
--     relation "takillak_irudiak" does not exist
--     column "id_takilla" of relation "powerbank" does not exist
--     invalid input value for enum egoera_takillak: "mantentze_lanetan"
--
--   Fitxategi honek datu-base zahar hori gaur egungo eskemara eguneratzen du,
--   daturik galdu gabe (irudiak beste taula batera mugitzen dira).
--
-- ERABILERA:
--   1) Babeskopia egin lehenago:
--        pg_dump -U postgres -Fc -f babeskopia.dump <datu-basea>
--   2) Exekutatu:
--        psql -U postgres -d <datu-basea> -f database/markel_eguneratu.sql
--   3) (aukerakoa) Datu adibideak gehitu:
--        psql -U postgres -d <datu-basea> -f database/seed.sql
--
--   Behin baino gehiagotan exekuta daiteke: dena idempotentea da.
-- ===========================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1) ERABILTZAILEAK: "activo" zutabea (erabiltzailea desaktibatzeko)
--    Zaharra ez zuenez, modeloaren SELECT/INSERT guztiek huts egiten zuten:
--    login-a barne.
-- ---------------------------------------------------------------------------
ALTER TABLE public.erabiltzaileak
    ADD COLUMN IF NOT EXISTS activo boolean NOT NULL DEFAULT true;

-- ---------------------------------------------------------------------------
-- 2) EGOERA-TAILAK: enum-balioak gaur egungo kodera egokitu
--    Zaharra:  'mantentze-lanetan', 'zerbitzuz kanpo'   (marra eta zuriunea)
--    Berria:   'mantentze_lanetan', 'zerbitzuz_kanpo'   (azpimarra)
--    Kodeak balio berriak bidaltzen ditu, eta Postgres-ek "invalid input value
--    for enum" errorea ematen zuen.
-- ---------------------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_enum e
        JOIN pg_type t ON t.oid = e.enumtypid
        WHERE t.typname = 'egoera_takillak' AND e.enumlabel = 'mantentze-lanetan'
    ) AND NOT EXISTS (
        SELECT 1 FROM pg_enum e
        JOIN pg_type t ON t.oid = e.enumtypid
        WHERE t.typname = 'egoera_takillak' AND e.enumlabel = 'mantentze_lanetan'
    ) THEN
        ALTER TYPE public.egoera_takillak RENAME VALUE 'mantentze-lanetan' TO 'mantentze_lanetan';
    END IF;

    IF EXISTS (
        SELECT 1 FROM pg_enum e
        JOIN pg_type t ON t.oid = e.enumtypid
        WHERE t.typname = 'egoera_takillak' AND e.enumlabel = 'zerbitzuz kanpo'
    ) AND NOT EXISTS (
        SELECT 1 FROM pg_enum e
        JOIN pg_type t ON t.oid = e.enumtypid
        WHERE t.typname = 'egoera_takillak' AND e.enumlabel = 'zerbitzuz_kanpo'
    ) THEN
        ALTER TYPE public.egoera_takillak RENAME VALUE 'zerbitzuz kanpo' TO 'zerbitzuz_kanpo';
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 3) KARGAGUNEEN IRUDIAK: "takillak.irudia" --> "takillak_irudiak" taula
--    Eskema berrian kargagune batek irudi bat baino gehiago izan ditzake, eta
--    taula independente batean gordetzen dira.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.takillak_irudiak (
    id_irudi integer GENERATED BY DEFAULT AS IDENTITY,
    id_takilla integer NOT NULL,
    url character varying(500) NOT NULL,
    CONSTRAINT takillak_irudiak_pkey PRIMARY KEY (id_irudi),
    CONSTRAINT takillak_irudiak_id_takilla_fkey
        FOREIGN KEY (id_takilla) REFERENCES public.takillak (id_takilla)
);

CREATE INDEX IF NOT EXISTS takillak_irudiak_id_takilla_idx
    ON public.takillak_irudiak (id_takilla);

-- Dauden irudiak taula berrira mugitu (errepikatu gabe).
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'takillak'
          AND column_name = 'irudia'
    ) THEN
        INSERT INTO public.takillak_irudiak (id_takilla, url)
        SELECT t.id_takilla, btrim(t.irudia)
        FROM public.takillak t
        WHERE t.irudia IS NOT NULL
          AND btrim(t.irudia) <> ''
          AND NOT EXISTS (
              SELECT 1 FROM public.takillak_irudiak i
              WHERE i.id_takilla = t.id_takilla AND i.url = btrim(t.irudia)
          );

        -- Zutabe zaharra kendu: modeloan ez da existitzen eta NOT NULL denez
        -- kargagune berriak sortzea eragozten zuen.
        ALTER TABLE public.takillak DROP COLUMN irudia;
    END IF;
END $$;

-- ---------------------------------------------------------------------------
-- 4) POWERBANK-AK: "id_takilla" zutabea
--    Powerbank-ak takilla batean edo postu batean egon daiteke. Modeloak beti
--    irakurtzen du zutabe hau, beraz falta bazen zerrenda osoa erortzen zen.
-- ---------------------------------------------------------------------------
ALTER TABLE public.powerbank
    ADD COLUMN IF NOT EXISTS id_takilla integer;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'powerbank_id_takilla_fkey'
    ) THEN
        ALTER TABLE public.powerbank
            ADD CONSTRAINT powerbank_id_takilla_fkey
            FOREIGN KEY (id_takilla) REFERENCES public.takillak (id_takilla);
    END IF;
END $$;

-- Dauden powerbank-etarako takilla postutik atera.
UPDATE public.powerbank p
SET id_takilla = po.id_takilla
FROM public.postuak po
WHERE po.id_postu = p.id_postu
  AND p.id_takilla IS NULL;

-- ---------------------------------------------------------------------------
-- 5) ROLAK: 1 = Administratzailea, 2 = Erabiltzailea
--    Kodeak id_rol == 1 erabiltzen du admin-a jakiteko (izena ez du axola),
--    baina rolak falta badira ezin da erabiltzailerik sortu (FK).
-- ---------------------------------------------------------------------------
INSERT INTO public.rolak (id_rol, rol_izena) VALUES
    (1, 'Administratzailea'),
    (2, 'Erabiltzailea')
ON CONFLICT (id_rol) DO NOTHING;

COMMIT;

